<script>
(function () {
  var reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;

  function fmt(el, n) {
    var d = +el.dataset.dec || 0;
    el.textContent = (el.dataset.prefix || '') +
      n.toLocaleString('pt-BR', { minimumFractionDigits: d, maximumFractionDigits: d }) +
      (el.dataset.suffix || '');
  }

  function count(el, delay) {
    var to = +el.dataset.to, dur = +el.dataset.dur || 1000;
    if (reduce) { fmt(el, to); return; }
    fmt(el, 0);
    setTimeout(function () {
      var t0 = performance.now();
      requestAnimationFrame(function step(t) {
        var p = Math.min((t - t0) / dur, 1);
        fmt(el, to * (1 - Math.pow(1 - p, 3)));
        if (p < 1) requestAnimationFrame(step);
      });
    }, delay || 0);
  }

  // Valor da carteira (hero): conta ao abrir a página
  document.querySelectorAll('.hero .count').forEach(function (el) { count(el, 300); });

  // Seções com .reveal: animam uma vez, quando aparecem na tela
  var blocks = document.querySelectorAll('.reveal');
  function show(el) {
    el.classList.add('in');
    el.querySelectorAll('.count').forEach(function (c) { count(c, 200); });
  }
  if (reduce || !('IntersectionObserver' in window)) {
    blocks.forEach(show);
  } else {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) { show(e.target); io.unobserve(e.target); }
      });
    }, { threshold: 0.35 });
    blocks.forEach(function (b) { io.observe(b); });
  }

  // Confete: estoura uma vez, quando a seção final aparece na tela
  var fin = document.querySelector('.final');
  var cv = document.getElementById('confetti');
  if (fin && cv && !reduce && 'IntersectionObserver' in window) {
    var ctx = cv.getContext('2d'), parts = [], raf = 0, W = 0, H = 0;
    var colors = ['#3b82f6', '#22c55e', '#eab308', '#ef4444', '#ffffff'];

    function size() {
      var dpr = window.devicePixelRatio || 1;
      W = fin.clientWidth; H = fin.clientHeight;
      cv.width = W * dpr; cv.height = H * dpr;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    }

    function wave(n) {
      var r = fin.getBoundingClientRect();
      var b = fin.querySelector('.btn').getBoundingClientRect();
      var ox = b.left - r.left + b.width / 2, oy = b.top - r.top;
      for (var i = 0; i < n; i++) {
        var a = -Math.PI / 2 + (Math.random() - 0.5) * Math.PI * 0.95;
        var v = 7 + Math.random() * 7;
        parts.push({
          x: ox, y: oy, vx: Math.cos(a) * v, vy: Math.sin(a) * v,
          w: 6 + Math.random() * 6, h: 3 + Math.random() * 4,
          rot: Math.random() * 6.28, vr: (Math.random() - 0.5) * 0.4,
          c: colors[i % colors.length], life: 0
        });
      }
      if (!raf) raf = requestAnimationFrame(tick);
    }

    function tick() {
      ctx.clearRect(0, 0, W, H);
      parts = parts.filter(function (p) { return p.y < H + 20 && p.life < 420; });
      parts.forEach(function (p) {
       p.vy += 0.02; p.vx *= 0.971; p.vy *= 0.975;
        p.x += p.vx; p.y += p.vy; p.rot += p.vr; p.life++;
        ctx.save();
        ctx.translate(p.x, p.y); ctx.rotate(p.rot);
       ctx.globalAlpha = Math.min(1, (420 - p.life) / 80);
        ctx.fillStyle = p.c;
        ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
        ctx.restore();
      });
      raf = parts.length ? requestAnimationFrame(tick) : 0;
    }

    var cio = new IntersectionObserver(function (entries) {
      if (entries[0].isIntersecting) {
        cio.disconnect();
        size();
        wave(80);
        setTimeout(function () { wave(60); }, 300);
      }
    }, { threshold: 0.6 });
    cio.observe(fin);
  }
})();
