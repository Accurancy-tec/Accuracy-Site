    <h2>1. Quem cuida dos seus dados</h2>
    <p>
        A equipe do projeto Accuracy (TCC da ETEC) é responsável pelo tratamento dos dados pessoais coletados
        no site e no aplicativo, seguindo a Lei Geral de Proteção de Dados (Lei nº 13.709/2018).
    </p>

    <h2>2. Quais dados coletamos</h2>
    <ul>
        <li><strong>Cadastro:</strong> nome, e-mail e senha (guardada de forma criptografada, com hash). Telefone, CPF e foto de perfil, se você escolher informar.</li>
        <li><strong>Login com Google:</strong> nome e e-mail da sua conta Google, se você usar essa opção.</li>
        <li><strong>Uso do simulador:</strong> carteiras, operações, metas, favoritos, notificações e progresso nos cursos.</li>
        <li><strong>Sessões:</strong> tipo de aparelho, navegador ou sistema e a data do último acesso, para mostrar a lista de aparelhos conectados e permitir desconectá-los.</li>
        <li><strong>Aceite destes documentos:</strong> a data e a versão aceita.</li>
    </ul>

    <h2>3. Para que usamos</h2>
    <ul>
        <li>criar sua conta, permitir o login e proteger o acesso;</li>
        <li>calcular saldos, carteiras, relatórios e a análise do Assistente Accuracy;</li>
        <li>enviar por e-mail os códigos de confirmação de cadastro e de recuperação de senha;</li>
        <li>avisar sobre metas atingidas e operações feitas na sua conta.</li>
    </ul>

    <h2>4. Com quem compartilhamos</h2>
    <p>Não vendemos nem alugamos dados. Usamos alguns serviços para o sistema funcionar:</p>
    <ul>
        <li><strong>Supabase</strong>, onde fica o banco de dados;</li>
        <li><strong>Render</strong>, que hospeda o servidor da API;</li>
        <li><strong>Brevo</strong>, que envia os e-mails com códigos;</li>
        <li><strong>Google</strong>, apenas se você entrar com a conta Google;</li>
        <li><strong>brapi</strong>, que fornece as cotações (não recebe seus dados pessoais).</li>
    </ul>

    <h2>5. Dados guardados no seu navegador ou aparelho</h2>
    <p>
        O site e o aplicativo guardam no próprio navegador ou aparelho os códigos de acesso da sessão e algumas
        preferências, como o tema claro ou escuro. Não usamos cookies de publicidade nem de rastreamento.
    </p>

    <h2>6. Segurança</h2>
    <p>
        As senhas são guardadas com hash, a comunicação com a API usa HTTPS, os códigos de acesso expiram em
        15 minutos e cada sessão pode ser encerrada a qualquer momento em <em>Aparelhos conectados</em>.
    </p>

    <h2>7. Seus direitos</h2>
    <p>
        Você pode confirmar quais dados temos, acessá-los, corrigi-los, pedir a exclusão da conta e revogar
        este consentimento. Boa parte disso está no seu perfil; o restante pode ser pedido pela página de
        <a href="suporte.php">Suporte</a>.
    </p>

    <h2>8. Por quanto tempo guardamos</h2>
    <p>
        Os dados ficam guardados enquanto a conta existir. Ao fim do projeto acadêmico, as contas e os dados
        podem ser apagados.
    </p>

    <h2>9. Menores de idade</h2>
    <p>
        Menores de 18 anos devem usar o Accuracy com o conhecimento e a autorização dos pais ou responsáveis.
    </p>

    <h2>10. Mudanças nesta política</h2>
